"""Select native run checkpoints for Git LFS without moving training files."""

import filecmp
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
NUMBERED = re.compile(r"step_(\d+)\.pth")
LIMIT = 100
# Retain these runs even after a newer run is trained in the same directory.
PINNED = {
    "train_20261122T233600Z_003e41",  # Isaac walk_lateral_random_vx report
    "train_20261119T051402_cfd7ef",   # DDPG cycle mean
    "train_20261119T075235_8d51a1",   # DDPG step narrow
    "train_20261121T060052_2cbf68",   # DDPG step wide
    "train_20261122T064052_ca66c2",   # DDPG walk only
}


def experiment_roots():
    ddpg = {}
    for descriptor in sorted((ROOT / "ddpg_webots/experiments").glob("*/config.json")):
        cfg = json.loads(descriptor.read_text(encoding="utf-8-sig"))
        root = (descriptor.parent / cfg["runs_root"]).resolve()
        root.relative_to(ROOT / "ddpg_webots/data")
        ddpg.setdefault(root, []).append(descriptor.parent.name)
    for root, names in ddpg.items():
        yield root, names
    for folder in sorted((ROOT / "sac_webots/data/experiments").glob("*/config.json")):
        yield folder.parent / "runs", [folder.parent.name]
    for folder in sorted((ROOT / "sac_isaac_lab/experiments").glob("*/*")):
        if folder.is_dir() and not folder.name.startswith((".", "__")):
            yield folder / "runs", [folder.name]
            if (folder / "multi_gpu_runs").is_dir():
                yield folder / "multi_gpu_runs", [folder.name + " (multi-GPU)"]


def numbered_files(folder):
    return sorted(
        (int(match[1]), path) for path in folder.glob("step_*.pth")
        if (match := NUMBERED.fullmatch(path.name)) and path.is_file()
    )


def copy_snapshot(source, target):
    if target.is_file() and filecmp.cmp(source, target, shallow=False):
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=target.parent, delete=False) as temp:
        staging = Path(temp.name)
    try:
        before = source.stat()
        shutil.copyfile(source, staging)
        after = source.stat()
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
            raise RuntimeError(f"Checkpoint changed during export: {source}")
        os.replace(staging, target)
    finally:
        staging.unlink(missing_ok=True)


def write_selection(path, content):
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                     dir=path.parent, delete=False) as f:
        f.write(content)
    os.replace(f.name, path)


def export_run(run, numbered, recovery):
    out = run / "checkpoints"
    newest_step, latest = numbered[-1] if numbered else (-1, None)
    recovery_time = None
    if recovery.is_file():
        import torch

        recovery_time = recovery.stat().st_mtime_ns
        state = torch.load(recovery, map_location="meta", weights_only=True)
        if int(state["env_steps"]) >= newest_step:
            latest = recovery
    if recovery_time is not None and recovery.stat().st_mtime_ns != recovery_time:
        raise RuntimeError(f"Recovery changed during export: {run}")
    copy_snapshot(latest, out / "latest.pth")
    rules = ["# Generated by tools/export_run_models.py", "!/latest.pth"]
    rules.extend("!/" + path.name for _, path in numbered[-LIMIT:])
    write_selection(out / ".gitignore", "\n".join(rules) + "\n")
    # Ignore rules apply only to untracked files. Retire older tracked steps
    # from the index while leaving their original checkpoint files on disk.
    ignored = subprocess.check_output(
        ["git", "ls-files", "-ci", "--exclude-standard", "-z", "--", "step_*.pth"], cwd=out)
    retired = [name for name in os.fsdecode(ignored).split("\0") if NUMBERED.fullmatch(name)]
    if retired:
        subprocess.run(["git", "rm", "--cached", "--", *retired], cwd=out, check=True)


def main():
    for root, names in experiment_roots():
        candidates = {}
        for pattern in ("train_*", "config_*/train_*"):
            for run in root.glob(pattern):
                # A checkout containing only published weights is not a training machine.
                if not (run / "training.csv").is_file():
                    continue
                folder = run / "checkpoints"
                numbered = numbered_files(folder)
                recovery = folder / "recovery_latest.pth"
                if numbered or recovery.is_file():
                    candidates[run] = (numbered, recovery)
        if not candidates:
            print(f"No local training checkpoints: {', '.join(names)}")
            continue
        # Continuing an older run can make it newer than a later fresh start.
        def last_save(run):
            numbered, recovery = candidates[run]
            files = [p for _, p in numbered]
            if recovery.is_file():
                files.append(recovery)
            return max(p.stat().st_mtime_ns for p in files), run.name

        newest = max(candidates, key=last_save)
        for run, (numbered, recovery) in candidates.items():
            keep = run == newest or run.name in PINNED or (run / "checkpoints/latest.pth").is_file()
            # DDPG profiles can share one runs_root but represent distinct experiments.
            if keep or len(names) > 1:
                export_run(run, numbered, recovery)
        write_selection(root / "latest_run.txt", newest.relative_to(root).as_posix() + "\n")
        print(f"{', '.join(names)}: {newest.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
